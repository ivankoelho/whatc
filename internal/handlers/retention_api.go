// Administrator-facing retention API. Reading needs settings.general:read, changing a policy or placing /
// revoking a hold needs settings.general:write; every query is scoped to the caller's organization.
// Nothing here deletes anything, and the simulation does not even write.

// Categories that are NOT configurable here, and why (shown to administrators so nobody assumes them).
var retentionNotCovered = []string{
	"nextcloud_originals", // the original stays in the person's Nextcloud: WhatC only holds a copy (covered by the category it was imported into)
	"meta_hosted_media",   // hosted by Meta: no bytes here, no way to delete from WhatC
	"ivr_audio",           // configuration in use by call flows, not user records
	"call_recordings",     // object storage, generated by the system: needs its own rule
	"exports",             // never stored: built in memory and handed over
	"audit_logs",          // never removed together with files: needs its own policy
	"protocol_history",    // the record of the protocol and its minimised data are not files
}

type retentionPolicyView struct {
	Category   string     `json:"category"`
	Enabled    bool       `json:"enabled"`
	KeepMonths int        `json:"keep_months"`
	UpdatedAt  *time.Time `json:"updated_at,omitempty"`
	UpdatedBy  string     `json:"updated_by,omitempty"`
}

// GetRetention returns the organization's rules per category (a category never configured shows as
// disabled with no term), the categories that are out of scope, and the state of the engine.
func (a *App) GetRetention(r *fastglue.Request) error {
	orgID, _, err := a.requireAuth(r, models.ResourceSettingsGeneral, models.ActionRead)
	if err != nil {
		return nil
	}
	var rows []models.RetentionPolicy
	a.DB.Where("organization_id = ?", orgID).Find(&rows)
	by := map[string]models.RetentionPolicy{}
	var actors []uuid.UUID
	for _, p := range rows {
		by[p.Category] = p
		if p.UpdatedByID != nil {
			actors = append(actors, *p.UpdatedByID)
		}
	}
	names := a.chatUserNames(actors)
	views := make([]retentionPolicyView, 0, len(models.RetentionCategories))
	for _, c := range models.RetentionCategories {
		v := retentionPolicyView{Category: c}
		if p, ok := by[c]; ok {
			v.Enabled, v.KeepMonths = p.Enabled, p.KeepMonths
			t := p.UpdatedAt
			v.UpdatedAt = &t
			if p.UpdatedByID != nil {
				v.UpdatedBy = names[*p.UpdatedByID]
			}
		}
		views = append(views, v)
	}
	return r.SendEnvelope(map[string]any{
		"policies":    views,
		"not_covered": retentionNotCovered,
		// The purge engine is built but cannot delete in this release: no setting turns it on.
		"engine": map[string]any{"execution_enabled": purgeExecutionEnabled},
	})
}

// PutRetentionPolicy sets one category's term and on/off switch.
func (a *App) PutRetentionPolicy(r *fastglue.Request) error {
	orgID, userID, err := a.requireAuth(r, models.ResourceSettingsGeneral, models.ActionWrite)
	if err != nil {
		return nil
	}
	category, _ := r.RequestCtx.UserValue("category").(string)
	if _, ok := retentionCategories[category]; !ok {
		return r.SendErrorEnvelope(fasthttp.StatusBadRequest, "Unknown retention category", nil, "")
	}
	var req struct {
		KeepMonths int  `json:"keep_months"`
		Enabled    bool `json:"enabled"`
	}
	if err := a.decodeRequest(r, &req); err != nil {
		return nil
	}
	if req.KeepMonths < 0 || req.KeepMonths > 600 {
		return r.SendErrorEnvelope(fasthttp.StatusBadRequest, "The term must be between 1 and 600 months", nil, "")
	}
	if req.Enabled && req.KeepMonths < 1 {
		return r.SendErrorEnvelope(fasthttp.StatusBadRequest, "Set a term in months before enabling the policy", nil, "")
	}

	var p models.RetentionPolicy
	before := map[string]any{"enabled": false, "keep_months": 0}
	found := a.DB.Where("organization_id = ? AND category = ?", orgID, category).First(&p).Error == nil
	if found {
		before = map[string]any{"enabled": p.Enabled, "keep_months": p.KeepMonths}
		p.KeepMonths, p.Enabled, p.UpdatedByID = req.KeepMonths, req.Enabled, &userID
		err = a.DB.Save(&p).Error
	} else {
		p = models.RetentionPolicy{ID: uuid.New(), OrganizationID: orgID, Category: category, KeepMonths: req.KeepMonths, Enabled: req.Enabled, UpdatedByID: &userID}
		err = a.DB.Create(&p).Error
	}
	if err != nil {
		return r.SendErrorEnvelope(fasthttp.StatusInternalServerError, "Failed to save the policy", nil, "")
	}
	a.logAudit(orgID, userID, "retention_policy", p.ID, models.AuditActionUpdated, before,
		map[string]any{"category": category, "enabled": p.Enabled, "keep_months": p.KeepMonths}, map[string]any{"field": "category", "new_value": category})
	return r.SendEnvelope(retentionPolicyView{Category: category, Enabled: p.Enabled, KeepMonths: p.KeepMonths, UpdatedAt: &p.UpdatedAt})
}

// SimulateRetention shows what each category's rule would make eligible. Strictly read-only: it writes
// nothing (not even a log row), removes nothing and queues nothing. A term can be tried without saving it.
func (a *App) SimulateRetention(r *fastglue.Request) error {
	orgID, _, err := a.requireAuth(r, models.ResourceSettingsGeneral, models.ActionRead)
	if err != nil {
		return nil
	}
	var req struct {
		Categories []string       `json:"categories"`
		Months     map[string]int `json:"months"` // what-if terms, per category
	}
	if len(r.RequestCtx.PostBody()) > 0 {
		if err := a.decodeRequest(r, &req); err != nil {
			return nil
		}
	}
	cats := req.Categories
	if len(cats) == 0 {
		cats = models.RetentionCategories
	}
	now := time.Now()
	out := make([]RetentionCategoryReport, 0, len(cats))
	for _, c := range cats {
		if _, ok := retentionCategories[c]; !ok {
			return r.SendErrorEnvelope(fasthttp.StatusBadRequest, "Unknown retention category", nil, "")
		}
		rep, err := a.evaluateRetention(orgID, c, req.Months[c], now, 50)
		if err != nil {
			a.Log.Error("Retention simulation failed", "category", c, "error", err)
			return r.SendErrorEnvelope(fasthttp.StatusInternalServerError, "The simulation failed", nil, "")
		}
		out = append(out, rep)
	}
	return r.SendEnvelope(map[string]any{
		"generated_at": now,
		"categories":   out,
		"note":         "read-only: nothing was changed, removed or queued",
	})
}
